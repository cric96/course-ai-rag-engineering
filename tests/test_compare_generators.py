import importlib.util
import json
import sys
from pathlib import Path
from types import SimpleNamespace

import pytest
from langchain_core.documents import Document
from langchain_core.runnables import RunnableLambda

spec = importlib.util.spec_from_file_location(
    "compare_generators", Path(__file__).parents[1] / "scripts/compare_generators.py"
)
experiment = importlib.util.module_from_spec(spec)
spec.loader.exec_module(experiment)


def test_comparison_uses_identical_inputs_and_keeps_paired_scores(
    tmp_path, monkeypatch
):
    output = tmp_path / "comparison.json"
    monkeypatch.setattr(
        sys,
        "argv",
        [
            "compare_generators.py",
            "--model",
            "fake:argon",
            "--sample",
            "2",
            "--output",
            str(output),
        ],
    )
    questions = [
        {
            "id": f"faq-{i}",
            "question": f"Question {i}",
            "answer": f"Answer {i}",
            "call": "a",
            "gold": [1],
        }
        for i in range(50)
    ]
    docs = [Document("A source passage", metadata={"title": "Source", "page": 1})]
    monkeypatch.setattr(experiment, "read_jsonl", lambda _: questions)
    monkeypatch.setattr(experiment, "load_pages", lambda: docs)
    for name in ["cache_embeddings", "cache_llm_calls", "cache_searches"]:
        monkeypatch.setattr(experiment, name, lambda: None)
    monkeypatch.setattr(experiment, "embedding_model", lambda _: None)
    searches = []

    class Store:
        client = SimpleNamespace(close=lambda: None)

        def as_retriever(self, search_kwargs):
            assert search_kwargs == {"k": 5}
            return self

        def invoke(self, question, **kwargs):
            searches.append(question)
            return docs

    monkeypatch.setattr(experiment, "vector_store", lambda *args: Store())
    generated = {}

    def model(name, **kwargs):
        def answer(prompt):
            if isinstance(prompt, str):
                return "OK"  # availability check
            generated.setdefault(name, []).append(prompt.to_string())
            return f"Generated by {name}"

        return RunnableLambda(answer)

    monkeypatch.setattr(experiment, "chat_model", model)
    monkeypatch.setattr(experiment, "judge_model", lambda name: name)
    metric_names = list(experiment.METRICS)
    monkeypatch.setattr(experiment, "correctness_metric", lambda _: metric_names[0])
    for constructor, name in zip(
        ["FaithfulnessMetric", "AnswerRelevancyMetric", "ContextualRecallMetric"],
        metric_names[1:],
        strict=True,
    ):
        monkeypatch.setattr(experiment, constructor, lambda name=name, **kwargs: name)

    def evaluate(cases, metrics, **kwargs):
        assert metrics == metric_names
        assert [c.input for c in cases[:2]] == [c.input for c in cases[2:]]
        assert all(c.retrieval_context == ["A source passage"] for c in cases)
        return SimpleNamespace(
            test_results=[
                SimpleNamespace(
                    name=case.name,
                    metrics_data=[
                        SimpleNamespace(
                            name=name, score=0.8 if i == 2 else 0.4, reason="Test"
                        )
                        for name in metric_names
                    ],
                )
                for i, case in enumerate(cases)
            ]
        )

    monkeypatch.setattr(experiment, "evaluate", evaluate)
    experiment.main()

    report = json.loads(output.read_text())
    assert len(searches) == 2  # retrieval happens once per question, not once per model
    assert sorted(generated[experiment.CHAT_MODEL]) == sorted(generated["fake:argon"])
    assert report["comparison"]["correctness_delta"] == pytest.approx(0.2)
    assert report["comparison"]["improved"] == 1
    assert report["comparison"]["unchanged"] == 1
    assert report["comparison"]["worse"] == 0
    assert report["runs"]["baseline"]["means"]["correttezza"] == 0.4
    assert report["runs"]["candidate"]["means"]["correttezza"] == pytest.approx(0.6)
    assert output.with_suffix(".svg").exists()


def test_fidelity_and_relevancy_use_only_questions_answered_by_both_models():
    def record(name, abstained, score):
        return {
            "id": name,
            "abstained": abstained,
            "scores": {"fedeltà": score, "pertinenza": score},
        }

    runs = {
        "baseline": {"records": [record("a", False, 0.7), record("b", True, 0)]},
        "candidate": {"records": [record("a", False, 0.8), record("b", False, 1)]},
    }
    shared = experiment.common_answered_metrics(runs)

    assert shared["ids"] == ["a"]
    assert shared["count"] == 1
    assert shared["means"]["baseline"]["fedeltà"] == 0.7
    assert shared["means"]["candidate"]["pertinenza"] == 0.8


def test_no_common_answers_means_fidelity_cannot_be_compared():
    run = {"records": [{"id": "a", "abstained": True, "scores": {}}]}
    shared = experiment.common_answered_metrics({"baseline": run, "candidate": run})

    assert shared["count"] == 0
    assert shared["means"]["baseline"]["fedeltà"] is None
